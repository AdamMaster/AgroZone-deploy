// Фиксированные тестовые пользователи для E2E-прогонов.
//
// Создаются один раз в globalSetup (../global-setup.ts) напрямую в БД
// через server/scripts/create-verified-user.ts (npm-скрипт
// test:e2e:create-user) — то есть с уже подтверждённым телефоном и без
// единого реального звонка через Zvonok. Номера заведомо фейковые
// (+7 999 000-00-0N — блок номеров, который не выдают реальным
// абонентам) и существуют только внутри тестовой БД greenbase_test,
// поэтому их не нужно скрывать/ротировать как секрет.
//
// PRIMARY используется в специках, которые НЕ ломают его исходное
// состояние необратимо для повторного прогона (login.spec.ts — только
// читает; email-change.spec.ts — каждый раз просто привязывает НОВую
// случайную почту поверх старой, что поддерживается приложением и не
// мешает следующему прогону).
//
// SECONDARY используется только в password-change.spec.ts, который меняет
// пароль пользователя, а затем сам возвращает его обратно в конце теста —
// см. комментарий в этом файле. Разделение на двух разных пользователей
// нужно, чтобы файлы спеков можно было гонять по отдельности, не только
// всем набором сразу, не боясь, что один спек незаметно испортит
// исходные данные для другого.
export interface TestUser {
  phone: string
  password: string
  name: string
}

export const PRIMARY_TEST_USER: TestUser = {
  phone: '+79990000001',
  password: 'e2eTestPass1',
  name: 'E2E Основной Пользователь'
}

export const SECONDARY_TEST_USER: TestUser = {
  phone: '+79990000002',
  password: 'e2eTestPass2',
  name: 'E2E Второй Пользователь'
}
