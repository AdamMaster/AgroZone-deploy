// Ключи — значения enum Prisma PriceUnit (server/prisma/schema.prisma), они
// приходят с бэка именно в таком регистре (ad.unit: 'KG', 'TON', ...), а не
// в нижнем — раньше здесь были ключи в нижнем регистре и словарь ни разу не
// срабатывал. Значения — винительный падеж ("за Тонну" → "за тонну"), чтобы
// использовать напрямую в фразах вида `за ${PRICE_UNITS[unit].toLowerCase()}`.
// Исключение — ITEM: раньше было "Штуку" ("за штуку" звучит бессмысленно
// для земельного участка — "за штуку чего?"), а по факту ITEM везде означает
// "цена целиком, без разбивки на единицы измерения" (трактор, участок,
// голова скота одним лотом и т.п.). Суффикс "за X" для ITEM теперь нигде не
// рендерится (см. ad-detail.tsx/ad-moderation-detail.tsx — там ITEM явно
// исключён из условия показа), а "Целиком" остаётся только для пикера
// единицы цены в форме объявления и в фильтре.
