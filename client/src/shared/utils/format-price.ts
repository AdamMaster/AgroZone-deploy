import { PRICE_UNITS_SHORT } from '@/shared/constants/units'

const NO_PRICE_LABEL = 'Цена договорная'

// Единственное место, где решается, как выглядит цена в интерфейсе. До этого
// каждая карточка форматировала её сама, и варианты разъехались: на странице
// объявления и в админке было `toLocaleString('ru-RU')`, а в карточках выдачи
// и в избранном — простая склейка строк, из-за которой цена выводилась как
// «4500000₽». Такое число не читается: «4500000» на глаз не отличить от
// «450000», а для оптовой площадки это разница в десять раз.
//
// Отсутствие цены и ноль трактуются одинаково — «Цена договорная»: ровно так
// же, как было во всех карточках до этой правки (там стояла проверка на
// истинность), и так же, как это понимает продавец, оставивший поле пустым.
export function formatPrice(price: number | null | undefined): string {
  if (!price) return NO_PRICE_LABEL

  return `${price.toLocaleString('ru-RU')} ₽`
}

// Цена вместе с единицей измерения: «14 200 ₽/т», «18 ₽/кг».
//
// Для агроплощадки это не украшение, а обязательная часть цены: «пшеница
// 14 200 ₽» без единицы нельзя ни с чем сравнить — это за тонну или за
// центнер? Поле ad.unit заполняется ещё в форме подачи (см. ad-form.tsx) и
// давно приходит с бэкенда, но в карточках просто не выводилось.
//
// Неизвестная единица или ITEM («цена целиком» — трактор, участок, партия
// одним лотом) суффикса не получают: у них его нет по смыслу.
export function formatPriceWithUnit(price: number | null | undefined, unit?: string | null): string {
  const formatted = formatPrice(price)

  if (!price || !unit) return formatted

  const short = PRICE_UNITS_SHORT[unit]

  return short ? `${formatted}/${short}` : formatted
}
