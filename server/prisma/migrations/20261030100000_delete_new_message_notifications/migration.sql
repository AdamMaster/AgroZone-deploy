-- Новые сообщения больше не создают уведомлений (о них сообщает счётчик
-- непрочитанного в «Сообщениях» и письмо). Убираем накопившиеся старые
-- записи, чтобы они не висели в списке уведомлений. Значение NEW_MESSAGE
-- в enum остаётся — убирать его из типа не нужно.
DELETE FROM "notifications" WHERE "type" = 'NEW_MESSAGE';
