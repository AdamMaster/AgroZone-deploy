-- «Поколение» входов пользователя (см. User.sessionVersion): при смене и сбросе
-- пароля увеличивается, и все прочие сессии перестают действовать. У уже
-- открытых сессий номера нет — он считается нулевым, поэтому после миграции
-- никого не разлогинит.
ALTER TABLE "users" ADD COLUMN "session_version" INTEGER NOT NULL DEFAULT 0;
