// Фото в одном сообщении чата по объявлению.
export const CHAT_MAX_PHOTOS = 5

// Размер одного фото до перекодирования — как у фото объявлений: телефон
// отдаёт оригинал в 3–8 МБ, 10 МБ с запасом, а всё, что больше, — не фото.
export const CHAT_MAX_FILE_SIZE = 10 * 1024 * 1024

// Письмо о новом сообщении уходит на первое непрочитанное: пока получатель не
// открыл диалог, следующие сообщения того же отправителя письма не шлют, а
// через это время напоминают снова.
export const CHAT_EMAIL_COOLDOWN_MS = 6 * 60 * 60 * 1000

// Ограничения на аккаунт против спама и почтовой бомбардировки получателя.
// Новый диалог — по объявлению, обычно один-два раза в день, а не десятки.
export const CHAT_START_THROTTLE = { default: { limit: 15, ttl: 60 * 60 * 1000 } }
// Живая переписка с фото укладывается в полсотни сообщений в минуту с запасом.
export const CHAT_SEND_THROTTLE = { default: { limit: 40, ttl: 60 * 1000 } }
