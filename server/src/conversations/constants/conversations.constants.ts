// Фото в одном сообщении чата по объявлению.
export const CHAT_MAX_PHOTOS = 5

// Размер одного фото до перекодирования — как у фото объявлений: телефон
// отдаёт оригинал в 3–8 МБ, 10 МБ с запасом, а всё, что больше, — не фото.
export const CHAT_MAX_FILE_SIZE = 10 * 1024 * 1024

// Письмо о новом сообщении планируется на первое непрочитанное: пока получатель
// не открыл диалог, следующие сообщения того же отправителя письма не порождают,
// а через это время напоминают снова.
export const CHAT_EMAIL_COOLDOWN_MS = 6 * 60 * 60 * 1000

// Через сколько после первого непрочитанного сообщения уходит письмо (если
// получатель к этому моменту так и не открыл диалог). Не короче времени,
// которое push через RuStore может идти до телефона: письмо не должно
// опережать уведомление и дублировать его тому, кто и так отвечает.
export const CHAT_EMAIL_DELAY_MS = 30 * 60 * 1000

// Воркер писем разбирает созревшие напоминания пачками: за раз не больше
// CHAT_EMAIL_BATCH_SIZE строк, пачек за запуск не больше CHAT_EMAIL_MAX_BATCHES
// (остаток подхватит следующий запуск), писем одновременно — не больше
// CHAT_EMAIL_CONCURRENCY, чтобы не перегрузить почтовый сервер.
export const CHAT_EMAIL_BATCH_SIZE = 100
export const CHAT_EMAIL_MAX_BATCHES = 10
export const CHAT_EMAIL_CONCURRENCY = 5

// Ограничения на аккаунт против спама и почтовой бомбардировки получателя.
// Новый диалог — по объявлению, обычно один-два раза в день, а не десятки.
export const CHAT_START_THROTTLE = { default: { limit: 15, ttl: 60 * 60 * 1000 } }
// Живая переписка с фото укладывается в полсотни сообщений в минуту с запасом.
export const CHAT_SEND_THROTTLE = { default: { limit: 40, ttl: 60 * 1000 } }
