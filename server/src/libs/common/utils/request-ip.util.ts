import { Request } from 'express'

// IP клиента для юридически значимых записей (сейчас — журнал согласий на
// обработку ПДн, см. PersonalDataConsent). В отличие от computeViewerKey
// (viewer-key.util.ts), где IP хэшируется и используется только для
// дедупа анонимных просмотров, здесь IP осознанно хранится в открытом
// виде — это и есть то доказательство "когда и откуда было дано
// согласие", ради которого весь журнал существует.
//
// req.ip корректно резолвит реальный IP клиента из X-Forwarded-For (а не
// адрес контейнера nginx), потому что `app.set('trust proxy', 1)` уже
// настроен в main.ts. Если это когда-нибудь перестанет быть верным
// (например, добавится ещё один прокси/CDN перед nginx) — здесь будет
// тихо записываться IP этого прокси, а не пользователя; в таком случае
// нужно поправить либо цепочку доверенных прокси в main.ts, либо этот
// файл.
export function getClientIp(req: Request): string {
  return req.ip ?? req.socket.remoteAddress ?? 'unknown'
}
