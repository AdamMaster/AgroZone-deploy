import pathlib

p = pathlib.Path("ROADMAP.md")
s = p.read_text(encoding="utf-8")

def replace_once(s, old, new):
    assert s.count(old) == 1, f"expected exactly 1 occurrence, got {s.count(old)}: {old[:80]!r}"
    return s.replace(old, new)

old = '- [ ] **F11 · средний — документы и сертификаты в объявлении.**'
new = ('- [ ] **F11 · средний — документы и сертификаты в объявлении.**\n'
       '  Отложено по решению владельца (08.09.2026): пункт из внешнего аудита\n'
       '  (без привязки к реальным продавцам сайта) — прикрепление к объявлению\n'
       '  сертификата/документа на товар (фитосанитарный сертификат, сертификат\n'
       '  соответствия на технику и т.п.). Полезно только когда на площадке уже\n'
       '  есть продавцы, которым есть чем подтверждать качество товара —\n'
       '  сейчас сайт только начинает жить, возврат по инициативе владельца при\n'
       '  реальном спросе.')

s = replace_once(s, old, new)
p.write_text(s, encoding="utf-8")
print("OK")
