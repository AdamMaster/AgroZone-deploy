import pathlib

p = pathlib.Path("ROADMAP.md")
s = p.read_text(encoding="utf-8")

old = """  **Осталось:** нужно накатить в БД — `npm run prisma:seed` из `server/`
  (upsert по стабильному id, ничего не удаляет и не ломает существующие
  категории/объявления — безопасно перезапускать)."""

new = """  **Осталось:** нужно накатить в БД — `npm run prisma:seed` из `server/`
  (upsert по стабильному id, ничего не удаляет и не ломает существующие
  категории/объявления — безопасно перезапускать).
  **Правка после сида (08.09.2026, по замечанию владельца):** у
  "Грузоперевозок" цена "за тонну" была первой/дефолтной в фильтре — по
  факту грузоперевозки почти никогда не оценивают по весу, цена зависит от
  маршрута/расстояния, а не только груза. Убрал `TON`, оставил только
  `ITEM` ("Целиком" — фиксированная/договорная цена без единицы, см.
  `shared/constants/units.ts`). Заодно проверил остальные 13 наборов
  единиц цены на реалистичность и поправил ещё одну: у "Услуги по убою и
  первичной переработке" (внутри общей группы `SERVICE_PROCESSING_FEATURES`
  с переработкой/фасовкой/производством под ТМ, где TON/KG уместны) убой
  на практике чаще оценивают за голову — переопределил `priceUnits` явно
  на этом узле на `['HEAD', 'KG', 'ITEM']`. Остальные наборы (поле — HA/
  HOUR, аренда/ремонт — HOUR, склад/хранение зерна — TON, консультации —
  ITEM первым) проверены и соответствуют реальной практике ценообразования
  в этих услугах."""

assert s.count(old) == 1, f"expected 1, got {s.count(old)}"
s = s.replace(old, new)
p.write_text(s, encoding="utf-8")
print("OK")
