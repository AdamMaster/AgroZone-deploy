import pathlib

p = pathlib.Path("ROADMAP.md")
s = p.read_text(encoding="utf-8")

def replace_once(s, old, new):
    assert s.count(old) == 1, f"expected exactly 1 occurrence, got {s.count(old)}: {old[:80]!r}"
    return s.replace(old, new)

old = '- [ ] **F7 · средний — объявления «Куплю» и запросы КП.**'
new = ('- [ ] **F7 · средний — объявления «Куплю» и запросы КП.**\n'
       '  Отложено по решению владельца (08.09.2026): по сути новая сторона\n'
       '  рынка с нуля — сейчас в схеме нет понятия типа объявления (всё неявно\n'
       '  "продаю"), нужен новый тип объявления «Куплю» + механизм откликов\n'
       '  продавцов на него (мини-система заявок, которой сейчас тоже нет).\n'
       '  Работает только при живом объёме покупателей и продавцов с обеих\n'
       '  сторон одновременно — сейчас рано. Возврат по инициативе владельца\n'
       '  при реальном росте аудитории.')

s = replace_once(s, old, new)
p.write_text(s, encoding="utf-8")
print("OK")
