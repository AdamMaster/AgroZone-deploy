import pathlib

p = pathlib.Path("ROADMAP.md")
s = p.read_text(encoding="utf-8")

def replace_once(s, old, new):
    assert s.count(old) == 1, f"expected exactly 1 occurrence, got {s.count(old)}: {old[:80]!r}"
    return s.replace(old, new)

old = '- [ ] **F5 · средний — сравнение техники по характеристикам.**'
new = ('- [ ] **F5 · средний — сравнение техники по характеристикам.**\n'
       '  Отложено по решению владельца (08.09.2026): полезно, когда в одной\n'
       '  подкатегории техники (тракторы/комбайны/навесное — у них уже есть\n'
       '  структурированные характеристики, см. `TECH_ATTACHED` в сидере) много\n'
       '  похожих объявлений одновременно — сейчас объём объявлений техники не\n'
       '  такой, сравнивать особо нечего. Возврат по инициативе владельца при\n'
       '  реальном росте числа объявлений в этих категориях.')

s = replace_once(s, old, new)
p.write_text(s, encoding="utf-8")
print("OK")
