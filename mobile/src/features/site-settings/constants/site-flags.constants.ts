import { SITE_FLAG_KEYS, type SiteFlags } from '../types/site-settings.types'

// Что видит пользователь, пока настоящие значения не получены (нет сети,
// сервер не ответил): всё новое выключено. Безопасная сторона отказа —
// функция, которая должна быть скрыта, не покажется по ошибке. Значения
// совпадают с SITE_FLAG_DEFAULTS на бэкенде.
export const DEFAULT_SITE_FLAGS: SiteFlags = {
  [SITE_FLAG_KEYS.SELLER_RATINGS]: false
}

export const SITE_FLAGS_QUERY_KEY = ['site-flags'] as const

// Флаги меняются раз в месяцы, а читаются при каждом запуске, поэтому
// держим их дольше общих 60 секунд: при возврате в приложение лишний
// запрос не нужен. Переключение из админки подхватывается в пределах этого
// срока — приложение пересобирать не требуется.
export const SITE_FLAGS_STALE_TIME_MS = 5 * 60_000

// Сколько сплэш ждёт флаги на запуске. Дольше ждать нельзя: без сети или при
// медленном ответе приложение должно открыться, а флаги подтянутся позже.
export const SITE_FLAGS_SPLASH_TIMEOUT_MS = 1500
